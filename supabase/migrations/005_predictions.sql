-- 005_predictions.sql: Tables to persist ML predictions (Sea-ice forecast & Iceberg drift trajectories)
CREATE TABLE IF NOT EXISTS public.sea_ice_predictions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90.0 AND 90.0),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180.0 AND 180.0),
    location GEOGRAPHY(Point, 4326) GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(longitude, latitude), 4326)::geography) STORED,
    prediction_time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    target_time TIMESTAMPTZ NOT NULL,
    predicted_concentration DOUBLE PRECISION NOT NULL CHECK (predicted_concentration BETWEEN 0.0 AND 100.0),
    confidence DOUBLE PRECISION DEFAULT 85.0,
    model_version TEXT DEFAULT 'v1.0',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.iceberg_trajectory_predictions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iceberg_id BIGINT NOT NULL REFERENCES public.icebergs(id) ON DELETE CASCADE,
    prediction_time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    target_time TIMESTAMPTZ NOT NULL,
    predicted_latitude DOUBLE PRECISION NOT NULL CHECK (predicted_latitude BETWEEN -90.0 AND 90.0),
    predicted_longitude DOUBLE PRECISION NOT NULL CHECK (predicted_longitude BETWEEN -180.0 AND 180.0),
    location GEOGRAPHY(Point, 4326) GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(predicted_longitude, predicted_latitude), 4326)::geography) STORED,
    probability DOUBLE PRECISION DEFAULT 0.85,
    model_version TEXT DEFAULT 'v1.2',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
